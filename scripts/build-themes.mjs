// Generates themes.css and keeps helper.css theme-ready.
//
// 1. Every raw colour in helper.css (#rgb, #rrggbb, #rrggbbaa) becomes a
//    CSS variable, e.g. #a4c2df -> var(--c-a4c2df). Running it twice is safe.
// 2. themes.css defines each variable three times:
//      :root                     Midnight notebook (the original colours, unchanged)
//      [data-theme='paper']      Paper journal (light)
//      [data-theme='coach']      Night coach (black + lime)
//    Paper and Coach colours are picked from each original colour's role
//    (background, card, line, muted text, text, accent, danger).
//
// Run: npm run themes
import { readFileSync, writeFileSync } from 'node:fs';

const HEX = /#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g;
const css = readFileSync('helper.css', 'utf8');
const converted = css.replace(HEX, (_, h) => `var(--c-${expand(h)})`);
writeFileSync('helper.css', converted);

const names = [...new Set([...converted.matchAll(/var\(--c-([0-9a-f]{6,8})\)/g)].map((m) => m[1]))];
names.push('8096ad', '122033'); // used by the progress graph in workout-progress.js

const palettes = {
  paper: {
    deep: '#efe7d6',
    bg: '#f5efe3',
    panel: '#fffaf0',
    line: '#e3d9c6',
    muted: '#6b6457',
    text: '#1d2a3c',
    accent: '#b9481a',
    accentSoft: '#8f3511',
    danger: '#b3261e',
  },
  coach: {
    deep: '#08090a',
    bg: '#0d0e10',
    panel: '#17191d',
    line: '#2a2d33',
    muted: '#9a9ea6',
    text: '#f4f4f0',
    accent: '#d4ff3a',
    accentSoft: '#eaff9e',
    danger: '#ff6b6b',
  },
};
// The main colours of Midnight, pinned to their role.
const pinned = {
  122033: 'bg',
  '0c1526': 'deep',
  '17273b': 'panel',
  152239: 'panel',
  142438: 'panel',
  304052: 'line',
  f0eadb: 'text',
  a5b3c4: 'muted',
  a4c2df: 'accent',
  '8096ad': 'muted',
};

function expand(h) {
  h = h.toLowerCase();
  if (h.length <= 4) h = [...h].map((c) => c + c).join('');
  return h;
}
function hsl(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b),
    min = Math.min(r, g, b),
    l = (max + min) / 2;
  const d = max - min;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  let h = 0;
  if (d) h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return { h: (h * 60 + 360) % 360, s, l };
}
function role(hex) {
  const rgb = hex.slice(0, 6);
  if (pinned[rgb]) return pinned[rgb];
  const { h, s, l } = hsl(rgb);
  if (s > 0.4 && (h >= 330 || h <= 20) && l > 0.3) return 'danger';
  if (s >= 0.35 && l >= 0.5) return l > 0.86 ? 'accentSoft' : 'accent';
  if (l < 0.12) return 'deep';
  if (l < 0.155) return 'bg';
  if (l < 0.3) return 'panel';
  if (l < 0.45) return 'line';
  if (l < 0.78) return 'muted';
  return 'text';
}
const value = (hex, palette) => palette[role(hex)] + (hex.length === 8 ? hex.slice(6) : '');
const block = (selector, fn) =>
  `${selector} {\n${names.map((n) => `  --c-${n}: ${fn(n)};`).join('\n')}\n}\n`;

writeFileSync(
  'public/themes.css',
  `/* Generated by scripts/build-themes.mjs. Do not edit by hand: run npm run themes. */\n` +
    block(':root', (n) => '#' + n) +
    block(":root[data-theme='paper']", (n) => value(n, palettes.paper)) +
    `:root[data-theme='paper'] { color-scheme: light; }\n` +
    block(":root[data-theme='coach']", (n) => value(n, palettes.coach)) +
    // Swatches in the theme picker always show their own theme's colours.
    `.theme-swatch-midnight { background: linear-gradient(135deg, #122033 50%, #a4c2df 50%); }\n` +
    `.theme-swatch-paper { background: linear-gradient(135deg, ${palettes.paper.bg} 50%, ${palettes.paper.accent} 50%); }\n` +
    `.theme-swatch-coach { background: linear-gradient(135deg, ${palettes.coach.bg} 50%, ${palettes.coach.accent} 50%); }\n`,
);
console.log(`themes.css: ${names.length} colours x 3 themes`);
